function per100g(
  fdcId: number,
  description: string,
  energy: number,
  protein: number,
  carbohydrate: number,
  fat: number,
): NutrientRow[] {
  const sourceName = `USDA FoodData Central, ${description}, FDC ${fdcId}, per 100 g`;
  return [
    { nutrient: 'energy', amount: energy, unit: 'kcal', sourceName },
    { nutrient: 'protein', amount: protein, unit: 'g', sourceName },
    { nutrient: 'carbohydrate', amount: carbohydrate, unit: 'g', sourceName },
    { nutrient: 'fat', amount: fat, unit: 'g', sourceName },
  ];
}

